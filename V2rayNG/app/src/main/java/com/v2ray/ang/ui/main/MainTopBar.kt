private const val ACCOUNT_URL = "https://kabinet.zazyvip.site"
private const val TELEGRAM_URL = "https://t.me/XControlBot_bot"

internal val ZaizyBrandTextStyle = TextStyle(
    color = Color(0xFFFFD47E),
    fontFamily = FontFamily.Serif,
    fontWeight = FontWeight.Bold,
    fontStyle = FontStyle.Italic,
    letterSpacing = 0.35.sp
)

@Composable
fun MainTopBar(
    isLoading: Boolean,
    showSearch: Boolean,
    searchQuery: String,
    onSearchQueryChange: (String) -> Unit,
    onSearchClose: () -> Unit,
    onMenuClick: () -> Unit,
    onAction: (MainAction) -> Unit
) {
    var showImportMenu by remember { mutableStateOf(false) }
    val importMenuScrollState = rememberScrollState()
    val statusBarHeight = WindowInsets.statusBars.asPaddingValues().calculateTopPadding()
    val navBarHeight = WindowInsets.navigationBars.asPaddingValues().calculateBottomPadding()
    val maxMenuHeight = LocalConfiguration.current.screenHeightDp.dp - statusBarHeight - navBarHeight - 20.dp

    AppTopBar(
        title = stringResource(R.string.app_name),
        titleContent = {
            Text(
                text = stringResource(R.string.app_name),
                style = MaterialTheme.typography.titleLarge.merge(ZaizyBrandTextStyle).copy(fontSize = 28.sp),
                maxLines = 1
            )
        },
        onBackClick = {},
        isLoading = isLoading,
        isSearchActive = showSearch,
        searchQuery = searchQuery,
        onSearchQueryChange = onSearchQueryChange,
        onSearchClose = onSearchClose,
        searchPlaceholder = stringResource(R.string.menu_item_search),
        navigationIcon = {
            if (showSearch) {
                IconButton(onClick = onSearchClose) {
                    Icon(painterResource(R.drawable.ic_arrow_back_24dp), contentDescription = stringResource(R.string.acc_back))
                }
            } else {
                IconButton(onClick = onMenuClick) {
                    Icon(painterResource(R.drawable.ic_menu_24dp), contentDescription = stringResource(R.string.acc_open_menu))
                }
            }
        },
        actions = {
            if (!showSearch) {
                IconButton(onClick = { onAction(MainAction.OpenSubscriptionLink(TELEGRAM_URL)) }) {
                    Icon(
                        painter = painterResource(R.drawable.ic_telegram_24dp),
                        contentDescription = "Telegram"
                    )
                }
            }
            IconButton(onClick = { onAction(MainAction.OpenSubscriptionLink(ACCOUNT_URL)) }) {
                Icon(
                    painter = painterResource(R.drawable.ic_zaizy_account),
                    contentDescription = stringResource(R.string.zaizy_account)
                )
            }
            Box(modifier = Modifier.wrapContentSize(Alignment.TopEnd)) {
                IconButton(onClick = { showImportMenu = true }) {
                    Icon(painterResource(R.drawable.ic_add_24dp), contentDescription = stringResource(R.string.acc_add))
                }
                DropdownMenu(
                    expanded = showImportMenu,
                    onDismissRequest = { showImportMenu = false },
                    scrollState = importMenuScrollState,
                    containerColor = MaterialTheme.colorScheme.surface,
                    modifier = Modifier
                        .heightIn(max = maxMenuHeight)
                        .verticalScrollbar(importMenuScrollState)
                ) {
                    ImportMenuContent(
                        onAction = { action ->
                            showImportMenu = false
                            onAction(action)
                        }
                    )
                }
            }
        }
    )
}
